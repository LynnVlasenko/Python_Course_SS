# Віддалені репозиторії

# Віддалені репозиторії не є дуже складними. В сучасному світі, де на кожному кроці можна зустріти "хмарні обчислення", може видатися, що концепція віддалених репозиторіїв є дуже складною, але насправді вони -- просто звичайні копії твого репозиторію на віддаленому комп’ютері. Зазвичай з цим віддаленим комп’ютером можна зв’язатися через інтернет, що дозволяє обмінюватись комітами.
# Приймаючи до уваги все сказане вище, віддалені репозиторії мають купу чудових властивостей:
# В першу чергу, віддалені сервери -- це завжди чудова резевна копія (бекап)! Локальний репозиторій дає можливість відкотитися до попереднього стану, але вся інформація зберігається локально. Маючи копії свого репозиторію на віддалених машинах, ти можеш пережити втрату жорсткого диску чи пошкодження данних і продовжити працювати з того місця, на якому закінчив.
# Що не менш важливо, віддалені репозиторії роблять програмування соціальним! Коли копія твого проекту розміщена в мережі, твої друзі мають змогу допомогти твоєму проекту (чи стягнути останні зміни) без зайвих зусиль.
# Стало дуже популярним користуватися веб-сайтами, що візуалізують активність на віддалених репозиторіях (наприклад GitHub), але віддалені репозиторії завжди слугують як основа цих сервісів. Тому важливо розуміти їх!


# Git Fetch

# Робота з віддаленими git-репозиторіями зводиться до передачі данних до та з інших репозиторіїв. Можливість передавати коміти дозволяє нам ділитися будь-якою інформацією, що відслідковується gitом (а отже, виконаною роботою, новими файлами, ідеями, листами, тощо).
# На цьому уроці ми навчимося витягати дані з віддаленого репозиторію -- команда, що відповідає за це, зручно називається git fetch (fetch - англ. витягнути чи дістати).
# Зауваж, що коли ми оновлюємо наш віддалений репозиторій, наші віддалені гілки теж оновляться. Про це ми говорили на попередньому уроці.

# Що робить fetch
# git fetch виконує дві основні дії, і тільки дві дії. Він:
# звантажує коміти, які містить віддалене сховище, але яких немає в локальному сховищі, та...
# оновлює посилання віддаленого бранчу (наприклад, o/main)
# Якщо коротко, git fetch приводить репрезентацію віддаленого репозиторію в локальному сховищі до актуального стану справжнього віддаленого репозиторію.
# Якщо ти пам’ятаєш з попереднього уроку, ми тоді зауважили, що віддалені гілки відображають стан віддаленого репозиторію від останнього разу, коли ми синхронізувались з віддаленим репозиторієм. git fetch якраз і відповідає за синхронізацію з віддаленим сховищем! Сподіваюсь, що зв’язок між віддаленими гілками git fetch тепер є очевидним.
# Як правило, git fetch працює з віддаленими сховищами через інтернет (через протоколи http:// чи git://).

# Чого не робить fetch
# Тим не менш, git fetch нічого не змінює в твоєму локальному стані. Він не оновить твою гілку main і не змінить того, як наразі виглядає локальна файлова система.
# Це важливо зрозуміти, тому що багато розробників думають, що git fetch оновить їхні локальні данні до стану віддаленого репозиторію. Він дійсно звантажить всі потрібні дані, щоб це зробити, але він не змінить автоматично жодних локальних файлів. Ми вивчимо команди, які це роблять, в наступних уроках :D
# Отже, зрештою, ти можеш вважати що git fetch просто звантажує нову інформацію з віддаленого сховища.


