# Git Revert
# Команда reset чудово працює для локальних бранчів на власному комп’ютері, 
# але так як вона спричиняє "переписування історії", її не можна використовувати в ситуації коли кілька користувачів працюють з цим бранчем
# Для того щоб відкотити зміни й потім поділитися цими відкоченими змінами з друзями, потрібно використовувати git revert.

# "перенесення змін" -- іншими словами, це можливість розробника переміщувати коміти між гілками в простий та зручний спосіб.

# Git Cherry-pick
# Перша команда в цій серії називається git cherry-pick. Вона має наступну форму:
