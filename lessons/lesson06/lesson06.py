# Відміна змін в Git
# Є декілька шляхів відмини змін в Git. 
# І так само як і коміти, зміни в гіт можна відміняти використовуючи або низькорівневі методи (додавання в коміт окремих файлів) так і високорівневі. 
# Є два основні шляхи відміни змін в Git -- перший це використовувати git reset й інший це git revert. 

# Git Reset
# git reset відміняє зміни переміщуючи вказівник гілки назад в історії на старіший коміт. 
# В принципі, можна вважати що це певне "переписування історії;" 
